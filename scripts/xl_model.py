from xl_common import *
import csv,os
out='model'
# CSV
names={'posts':'Post','rails36':'Rail36 face','rails72':'Rail72 face','joists':'Joist face','rafters':'Rafter','ring':'Ring'}
with open(f'{out}/gazebo_pixels.csv','w',newline='') as f:
    w=csv.writer(f);w.writerow(['index','channel_start','member','member_no','pos_in_member','x_in','y_in','z_in'])
    for n in range(N):
        w.writerow([n+1,3*n+1,names[MEM[n]],MIDX[n]+1,LOC[n]+1,*(f'{v:.2f}' for v in XYZ[n])])
# grid: 1 inch cells. col=x, layer=y(depth), row=from top
xs=np.round(XYZ[:,0]).astype(int);ys=np.round(XYZ[:,1]).astype(int);zs=np.round(XYZ[:,2]).astype(int)
xo,yo=xs.min(),ys.min();zmax=zs.max()
cells={};moved=0
for n in range(N):
    c=(xs[n]-xo,ys[n]-yo,zs[n])
    while c in cells:
        c=(c[0]+1,c[1],c[2]);moved+=1
    cells[c]=n+1
Wd=max(c[0] for c in cells)+1;D=max(c[1] for c in cells)+1;Hh=zmax+1
grid={}
for (cx,cy,cz),node in cells.items(): grid[(zmax-cz,cx,cy)]=node
layers=[]
for d in range(D):
    rows=[]
    for r in range(Hh):
        rows.append(','.join(str(grid.get((r,c,d),'')) for c in range(Wd)))
    layers.append(';'.join(rows))
data='|'.join(layers)
xml=f'''<?xml version="1.0" encoding="UTF-8"?>
<custommodel name="Gazebo" parm1="{Wd}" parm2="{Hh}" Depth="{D}" StringType="RGB Nodes" Transparency="0" PixelSize="2" ModelBrightness="" Antialias="1" StrandNames="" NodeNames="" PixelCount="{N}" PixelType="Nodes" PixelSpacing="2" SourceVersion="2025.12" CustomModel="{data}" >
</custommodel>
'''
open(f'{out}/gazebo.xmodel','w').write(xml)
print('grid',Wd,Hh,D,'collisions moved',moved,'bytes',len(xml))
